/// Нарисовать иконку целыми пикселями экрана: клетка = 1, 2, 3… физических пикселя,
/// иначе клетки получаются разной ширины и иконка выглядит размытой и кривой.
pub fn draw(p: &Painter, ic: Icon, r: Rect, c: Color32) {
    let ppp = p.ctx().pixels_per_point();
    let cell_px = (r.width().min(r.height()) * ppp / 12.0 - 0.15).round().max(1.0);
    let cell = cell_px / ppp;
    let side = cell * 12.0;
    let snap = |v: f32| (v * ppp).round() / ppp;
    let o = pos2(snap(r.center().x - side / 2.0), snap(r.center().y - side / 2.0));
    let half = c.gamma_multiply(0.45);
    // одним мешем: у rect_filled egui сглаживает края, ужимая фигуру на полпикселя, —
    // клетка шириной в один физический пиксель от этого пропадает совсем
    let mut mesh = Mesh::default();
    for (y, row) in art(ic).iter().enumerate() {
        for (x, ch) in row.bytes().enumerate() {
            let col = match ch {
                b'#' => c,
                b'+' => half,
                _ => continue,
            };
            let min = o + Vec2::new(x as f32, y as f32) * cell;
            mesh.add_colored_rect(Rect::from_min_size(min, Vec2::splat(cell)), col);
        }
    }
    p.add(Shape::mesh(mesh));
}

